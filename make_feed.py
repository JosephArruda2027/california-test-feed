"""Makes the California Test Show: three ~2-minute tone episodes (WAV), a chapters file and feed.xml.
Everything here is generated by this script (tones only), so it can be published under CC0."""
import json, math, os, struct, wave
from email.utils import format_datetime
from datetime import datetime, timedelta, timezone

BASE = 'https://josepharruda2027.github.io/california-test-feed'
RATE = 16000
HERE = os.path.dirname(os.path.abspath(__file__))


def episode(path, seconds, pitches):
    """A soft tone that changes pitch at each section, with a short click every 10 s so a skip of
    30 s can be heard; three falling beeps at the very end."""
    frames = bytearray()
    section = seconds / len(pitches)
    for i in range(seconds * RATE):
        t = i / RATE
        f = pitches[min(int(t // section), len(pitches) - 1)]
        v = 0.18 * math.sin(2 * math.pi * f * t)
        if t % 10 < 0.06:                       # click every 10 s
            v += 0.35 * math.sin(2 * math.pi * 1500 * t)
        if t > seconds - 1.5:                   # end beeps
            k = int((t - (seconds - 1.5)) / 0.5)
            v = 0.3 * math.sin(2 * math.pi * (880 - 200 * k) * t) if (t % 0.5) < 0.3 else 0
        frames += struct.pack('<h', int(max(-1, min(1, v)) * 32767))
    with wave.open(path, 'wb') as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(RATE); w.writeframes(bytes(frames))
    return os.path.getsize(path)


EPISODES = [
    (1, 'Episode 1: Low tones', 'Two minutes of low tones. A click every 10 seconds; three beeps at the end.', 120, [220, 247, 262, 294]),
    (2, 'Episode 2: Middle tones', 'Two minutes of middle tones. A click every 10 seconds; three beeps at the end.', 120, [330, 349, 392, 440]),
    (3, 'Episode 3: Three chapters', 'Two minutes in three chapters (Start, Middle, End), each its own tone.', 120, [262, 392, 523]),
]

now = datetime(2026, 10, 27, 9, 0, tzinfo=timezone.utc)
items = []
for n, title, desc, secs, pitches in EPISODES:
    name = f'episode{n}.wav'
    size = episode(os.path.join(HERE, name), secs, pitches)
    chapters = ''
    if n == 3:
        json.dump({'version': '1.2.0', 'chapters': [
            {'startTime': 0, 'title': 'Start'}, {'startTime': 40, 'title': 'Middle'}, {'startTime': 80, 'title': 'End'}]},
            open(os.path.join(HERE, 'episode3-chapters.json'), 'w'), indent=2)
        chapters = f'\n      <podcast:chapters url="{BASE}/episode3-chapters.json" type="application/json+chapters"/>'
    date = format_datetime(now - timedelta(days=3 - n))
    items.append(f'''    <item>
      <title>{title}</title>
      <description>{desc}</description>
      <guid isPermaLink="false">california-test-show-{n}</guid>
      <pubDate>{date}</pubDate>
      <enclosure url="{BASE}/{name}" length="{size}" type="audio/wav"/>
      <itunes:duration>{secs // 60}:{secs % 60:02}</itunes:duration>
      <itunes:episode>{n}</itunes:episode>{chapters}
    </item>''')

feed = f'''<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0" xmlns:itunes="http://www.itunes.com/dtds/podcast-1.0.dtd" xmlns:podcast="https://podcastindex.org/namespace/1.0">
  <channel>
    <title>California Test Show</title>
    <link>{BASE}/</link>
    <description>A made-up show for testing the California TV app's PODCASTS. Tones only. Not a real podcast.</description>
    <language>en-us</language>
    <itunes:author>California testing</itunes:author>
    <itunes:image href="{BASE}/cover.png"/>
    <itunes:category text="Technology"/>
    <itunes:explicit>false</itunes:explicit>
    <itunes:block>Yes</itunes:block>
    <podcast:locked>yes</podcast:locked>
{chr(10).join(reversed(items))}
  </channel>
</rss>
'''
open(os.path.join(HERE, 'feed.xml'), 'w', encoding='utf-8').write(feed)
print('feed.xml written')
